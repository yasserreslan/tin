#!/usr/bin/env python3
"""Regenerate bounded vector leaves from their relocation-free assembly sources."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
NAMES = ('memcpy', 'memmove', 'memset', 'memcmp', 'memchr')


def functions(path, wanted):
    data = path.read_bytes()
    shoff = struct.unpack_from('<Q', data, 40)[0]
    size, count = struct.unpack_from('<HH', data, 58)
    sections = [struct.unpack_from('<IIQQQQIIQQ', data, shoff+i*size) for i in range(count)]
    result = {}
    for s in sections:
        if s[1] in (4, 9) and s[5]:
            raise ValueError('memory leaves must have no relocations')
        if s[1] != 2:
            continue
        strings = sections[s[6]]
        names = data[strings[4]:strings[4]+strings[5]]
        for off in range(s[4], s[4]+s[5], s[9]):
            name, info, other, section, value, length = struct.unpack_from('<IBBHQQ', data, off)
            name = names[name:names.index(0, name)].decode()
            if name in wanted:
                start = sections[section][4] + value
                result[name] = data[start:start+length]
    assert set(result) == set(wanted)
    return result


def generate():
    text = ['// Generated by tools/gen/gen_memory_fast.py from tools/gen/arch/memory-fast-*.S.']
    with tempfile.TemporaryDirectory() as tmp:
        for arch, target in [('arm64', 'aarch64-linux-gnu'), ('amd64', 'x86_64-linux-gnu')]:
            obj = Path(tmp)/f'{arch}.o'
            subprocess.run(['clang', '-target', target, '-c', str(ROOT/f'tools/gen/arch/memory-fast-{arch}.S'), '-o', str(obj)], check=True)
            wanted = NAMES + (('mem_avx2_supported',) if arch == 'amd64' else ())
            table = functions(obj, wanted)
            vectors = {}  # the AVX2-capable variants (they read the core context in r15): every program has one
            if arch == 'amd64':
                subprocess.run(['clang', '-target', target, '-DMEMORY_VECTOR', '-c',
                    str(ROOT/f'tools/gen/arch/memory-fast-{arch}.S'), '-o', str(obj)], check=True)
                vectors = functions(obj, wanted)
            text += ['', f'fn memory_fast_{arch}(name str) i64 {{', '\tmut hex = ""']
            for name in wanted:
                data = (vectors[name] if name in ('memcpy', 'memmove', 'memcmp', 'memchr') and vectors else table[name])
                if arch == 'arm64':
                    data = ''.join(f'{v[0]:08x}' for v in struct.iter_unpack('<I', data))
                else:
                    data = data.hex()
                text += [f'\tif name == "{name}" {{', f'\t\thex = "{data}"', '\t}']
            text += ['\tlet v = []i64{}', '\tmut i = 0', '\tfor i < len(hex) {']
            if arch == 'arm64':
                text += ['\t\traw(cast([]i64, v), hex_word(hex, i))', '\t\ti = i + 8']
            else:
                text += ['\t\tv = append(v, num_digit(i64(hex[i])) * 16 + num_digit(i64(hex[i + 1])))', '\t\ti = i + 2']
            text += ['\t}', '\treturn cast(i64, v)', '}']
    return '\n'.join(text)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'selfhost/memory_fast.tin'
    result = generate()
    if args.check:
        assert path.read_text() == result, 'memory machine code is stale'
    else:
        path.write_text(result)
