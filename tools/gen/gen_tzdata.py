#!/usr/bin/env python3
"""Generate toolchain/std/tide/tzdata/tzdata.tin from the IANA time zone database (run from the
repo root).

    python3 tools/gen/gen_tzdata.py [DIR-OR-ZIP]

The default source is Go's lib/time/zoneinfo.zip ($(go env GOROOT)/lib/time/zoneinfo.zip), the
IANA database (public domain, https://www.iana.org/time-zones) as Go ships it; a directory (a
system /usr/share/zoneinfo, say) is read instead when one is given. The output is the nested
package tide/tzdata: import it for its side effect, like Go's time/tzdata, and tide.LoadZone
resolves names the system directories do not have, as in an empty container image.

The container is: u32 zone count; per zone, u32 name length, u32 data length, the name and the
TZif bytes (RFC 8536). It is deflated (RFC 1951, level 9) into string constants; tide/tzdata
inflates it on every core when its globals are set up and keeps each zone's bytes, and
tide.LoadZone parses one lazily when the system directories miss.

Budget: the packed stream stays under 128 KiB (about 80 KiB today) and the generated file under
1 MiB. The binary increase is measured on the Linux targets in the pull request.
"""
import os
import subprocess
import sys
import zipfile
import zlib

OUT = "toolchain/std/tide/tzdata/tzdata.tin"
CHUNK = 16000
BUDGET = 128 * 1024


def default_source():
    root = subprocess.run(["go", "env", "GOROOT"], capture_output=True, text=True, check=True).stdout.strip()
    return os.path.join(root, "lib", "time", "zoneinfo.zip")


def read_zip(path):
    with zipfile.ZipFile(path) as z:
        return [(i.filename, z.read(i.filename)) for i in z.infolist()
                if not i.is_dir() and not i.filename.endswith("/")]


def read_dir(path):
    out = []
    for root, dirs, files in os.walk(path):
        dirs[:] = sorted(d for d in dirs if d not in ("posix", "right"))
        for name in sorted(files):
            full = os.path.join(root, name)
            rel = os.path.relpath(full, path)
            if rel in ("posixrules", "leapseconds", "tzdata.zi", "iso3166.tab", "zone.tab",
                       "zone1970.tab", "zonenow.tab", "leap-seconds.list", "+VERSION", "VERSION"):
                continue
            if os.path.islink(full) and not os.path.exists(full):
                continue
            with open(full, "rb") as f:
                out.append((rel, f.read()))
    return out


def container(zones):
    """The packed container the Tin side reads: count, then name/data length pairs and bytes."""
    out = bytearray(len(zones).to_bytes(4, "little"))
    for name, data in zones:
        raw = name.encode()
        out += len(raw).to_bytes(4, "little")
        out += len(data).to_bytes(4, "little")
        out += raw
        out += data
    return bytes(out)


def escape(data):
    """One string literal's body: alphanumeric ASCII stays, every other byte is \\xNN."""
    out = []
    for b in data:
        c = chr(b)
        out.append(c if c.isalnum() and b < 128 else "\\x%02x" % b)
    return "".join(out)


def main():
    source = sys.argv[1] if len(sys.argv) > 1 else default_source()
    if source.endswith(".zip"):
        zones = read_zip(source)
    else:
        zones = read_dir(source)
    zones = [(n, d) for n, d in zones if d[:4] in (b"TZif",)]
    zones.sort()
    if not zones:
        raise SystemExit("gen_tzdata: no TZif files in " + source)
    packed = zlib.compressobj(9, zlib.DEFLATED, -15)
    stream = packed.compress(container(zones)) + packed.flush()
    if len(stream) > BUDGET:
        raise SystemExit(f"gen_tzdata: the packed stream is {len(stream)} bytes, over the "
                         f"{BUDGET} budget")
    bodies = [escape(stream[i:i + CHUNK]) for i in range(0, len(stream), CHUNK)]
    out = [
        "// Code generated by tools/gen/gen_tzdata.py from " + source + "; DO NOT EDIT.",
        "",
        "// Package tzdata embeds the IANA time zone database (public domain,",
        "// https://www.iana.org/time-zones) so that tide.LoadZone works in an image with no",
        "// /usr/share/zoneinfo: import it for its side effect, like Go's time/tzdata.",
        "//",
        "//\timport \"tide/tzdata\"",
        "//",
        "// Without it, LoadZone in an empty root fails with tide.ErrUnknownZone. With it, every name",
        "// in the database resolves from memory: the package installs the data on every core when its",
        "// globals are set up, before main, and LoadZone reads it after $ZONEINFO and the system",
        "// directories miss. The trade-off is size: the whole database is one DEFLATE stream of",
        "// %d KiB (%d zones), and a static binary grows by that much plus the name table; the" % (len(stream) // 1024, len(zones)),
        "// generator (tools/gen/gen_tzdata.py) enforces a 128 KiB budget on the stream. A program",
        "// that never imports this package pays nothing.",
        "package tzdata",
        "",
        "import \"tide\"",
        "",
        "// packedChunks hold the DEFLATE stream (RFC 1951) of the zone container: u32 count; per",
        "// zone, u32 name length, u32 data length, the name and the TZif bytes (RFC 8536). They are",
        "// chunks of one stream, no source line over 16 KiB.",
    ]
    out += ["const packed%d = \"%s\"" % (i, b) for i, b in enumerate(bodies)]
    out += [
        "",
        "// packed is the whole stream: the chunks concatenated.",
        "let packed = " + " + ".join("packed%d" % i for i in range(len(bodies))),
        "",
        "// registered installs the database on this core when the package's globals are set up.",
        "let registered = tide.RegisterEmbedded(packed)",
        "",
    ]
    text = "\n".join(out)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print(f"{OUT}: {len(zones)} zones, {len(stream)} bytes packed, {len(text)} bytes of source")


if __name__ == "__main__":
    main()
