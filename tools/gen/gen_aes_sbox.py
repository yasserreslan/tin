#!/usr/bin/env python3
"""Generate lib/seal/aes_sbox.tin: the AES S-box on eight bit planes, as straight-line code.

Plane i holds bit i of up to 64 bytes. The S-box is the inverse in GF(2^8) (x^254, mod
x^8 + x^4 + x^3 + x + 1) followed by the affine map with 0x63, computed with ANDs and XORs
only, so no table is indexed by data (the point of a constant-time AES)."""
import sys

lines = []
counter = [0]


def fresh():
    counter[0] += 1
    return f'v{counter[0]}'


def reduce(p):
    """Reduce 15 product planes (lists of terms) to 8, mod x^8 + x^4 + x^3 + x + 1."""
    for k in range(14, 7, -1):
        for d in (4, 5, 7, 8):
            p[k - d] = p[k - d] + p[k]
        p[k] = []
    out = []
    for k in range(8):
        # x ^ x = 0: keep only the terms that occur an odd number of times.
        terms = [t for t in dict.fromkeys(p[k]) if p[k].count(t) % 2 == 1]
        if not terms:
            out.append('u64(0)')
            continue
        if len(terms) == 1:
            out.append(terms[0])
            continue
        v = fresh()
        lines.append(f'\tlet {v} = ' + ' ^ '.join(terms))
        out.append(v)
    return out


def mul(a, b):
    p = [[] for _ in range(15)]
    for i in range(8):
        for j in range(8):
            v = fresh()
            lines.append(f'\tlet {v} = {a[i]} & {b[j]}')
            p[i + j].append(v)
    return reduce(p)


def sq(a):
    p = [[] for _ in range(15)]
    for i in range(8):
        p[2 * i].append(a[i])
    return reduce(p)


def main():
    x = [f'q{i}' for i in range(8)]
    for i in range(8):
        lines.append(f'\tlet q{i} = q[{i}]')
    x2 = sq(x)
    x3 = mul(x2, x)
    x6 = sq(x3)
    x12 = sq(x6)
    x15 = mul(x12, x3)
    x30 = sq(x15)
    x60 = sq(x30)
    x120 = sq(x60)
    x240 = sq(x120)
    x252 = mul(x240, x12)
    inv = mul(x252, x2)
    # The affine map: b_i = x_i ^ x_(i+4) ^ x_(i+5) ^ x_(i+6) ^ x_(i+7) ^ bit i of 0x63.
    for i in range(8):
        terms = [inv[(i + k) % 8] for k in (0, 4, 5, 6, 7)]
        expr = ' ^ '.join(terms)
        if (0x63 >> i) & 1:
            expr = f'^({expr})'
        lines.append(f'\tq[{i}] = {expr}')
    out = ['// Code generated by tools/gen/gen_aes_sbox.py; DO NOT EDIT.', '', 'package seal', '',
           '// aes_sbox applies the AES S-box to every byte held in the bit planes q[0..7], with',
           '// ANDs and XORs only (constant-time: no table, no branch).',
           'fn aes_sbox(q mut []u64) {'] + lines + ['}', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
